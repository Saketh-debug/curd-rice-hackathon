"""
laya_decision.py
================
Step 2 — Laya Decision Engine (replaces random.uniform fake confidence).

Laya is a structured, single-pass decision engine that:
  1. Computes a calibrated confidence score from real network-flow / telemetry
     features (no random dice rolls).
  2. Returns one of three typed actions:
       AUTO_BLOCK       — critical, ≥ auto_block_threshold confidence
       ESCALATE         — borderline, medium-high confidence
       MONITOR          — nominal / low confidence
  3. Identifies the top contributing features explaining WHY the record
     was flagged (feature explainability required by the problem statement).
  4. Optionally defers to a local Ollama / Laya LLM endpoint for natural
     language explanation enrichment (gracefully falls back to deterministic
     engine if Ollama is not available).

Usage:
    from laya_decision import laya_decide, LayaDecision
    decision = laya_decide(row_features, pred_class, auto_block_threshold=0.95)
    print(decision.action, decision.calibrated_confidence, decision.primary_factors)
"""

from __future__ import annotations

import math
import json
from dataclasses import dataclass, asdict, field
from typing import Any, Dict, List, Optional, Tuple

import numpy as np

# ── Return Type ────────────────────────────────────────────────────────────

@dataclass
class LayaDecision:
    """Structured decision returned by the Laya engine."""

    # One of: "AUTO_BLOCK", "ESCALATE_TO_ANALYST", "MONITOR"
    action: str

    # Calibrated probability score in [0, 1].  Deterministic — NOT random.
    calibrated_confidence: float

    # Top ≤ 3 factors explaining why flagged, e.g.:
    # [{"feature": "Flow Packets/s", "value": 52341, "contribution": 0.28, "note": "..."}]
    primary_factors: List[Dict[str, Any]]

    # Natural-language summary generated by embedded rule engine (or Laya LLM).
    explanation: str

    # Risk tier: "CRITICAL", "HIGH", "MEDIUM", "LOW"
    risk_tier: str

    # Raw per-dimension scores for debugging / audit trail
    _raw_scores: Dict[str, float] = field(default_factory=dict, repr=False)

    def to_dict(self) -> Dict[str, Any]:
        d = asdict(self)
        d.pop("_raw_scores", None)
        return d


# ── Network-flow feature weight map ───────────────────────────────────────
# Keys match (stripped) column names from large_simulation_log.csv / CICIDS2017.
# Values are (weight, direction, threshold) tuples where:
#   weight      — maximum contribution this feature can add to the score
#   direction   — "high" means anomalous when value is HIGH, "low" when LOW
#   threshold   — value above/below which the feature is considered active
_FLOW_FEATURE_WEIGHTS: List[Tuple[str, float, str, float]] = [
    # (column_name,                weight, direction, threshold)
    ("Flow Packets/s",             0.22,   "high",    30_000),
    ("Flow Bytes/s",               0.15,   "high",    5_000_000),
    ("Average Packet Size",        0.10,   "high",    1200),
    ("Fwd Packets/s",              0.10,   "high",    20_000),
    ("Bwd Packets/s",              0.10,   "high",    20_000),
    ("Fwd Packet Length Max",      0.08,   "high",    1400),
    ("ACK Flag Count",             0.07,   "high",    100),
    ("SYN Flag Count",             0.08,   "high",    50),
    ("FIN Flag Count",             0.05,   "high",    30),
    ("RST Flag Count",             0.07,   "high",    20),
    ("Init_Win_bytes_forward",     0.04,   "low",     512),
    ("min_seg_size_forward",       0.04,   "low",     8),
]

# Telemetry feature weight map (OPS-SAT / space anomaly features)
# Calibrated against actual training split statistics:
#   len           | anomaly median=184, normal median=53   | HIGH = anomalous
#   diff2_peaks   | anomaly median=5,   normal median=15   | LOW  = anomalous
#   diff_peaks    | anomaly median=2,   normal median=6    | LOW  = anomalous
#   diff2_var     | anomaly median=6.1e-11, normal=6.8e-12 | HIGH = anomalous
#   var_div_len   | anomaly median=3.1e-12, normal=2.1e-11 | LOW  = anomalous
_TELEMETRY_FEATURE_WEIGHTS: List[Tuple[str, float, str, float]] = [
    ("len",           0.30, "high",   150.0),
    ("diff2_peaks",   0.25, "low",    8.0),     # LOW diff2_peaks = anomalous
    ("diff_peaks",    0.20, "low",    4.0),     # LOW diff_peaks  = anomalous
    ("diff2_var",     0.15, "high",   5e-11),
    ("var_div_len",   0.10, "low",    3e-12),   # LOW var_div_len = anomalous
]


# ── Core scoring logic ─────────────────────────────────────────────────────

def _score_feature(value: float, direction: str, threshold: float) -> float:
    """Map a single feature value to a [0, 1] activation score."""
    if direction == "high":
        if value <= 0:
            return 0.0
        ratio = value / max(threshold, 1e-9)
        if ratio < 1.0:
            return float(np.clip(0.5 * ratio, 0.0, 0.5))
        else:
            return float(np.clip(0.5 + 0.5 * (1.0 - math.exp(-(ratio - 1.0))), 0.0, 1.0))
    elif direction == "low":
        # Anomalous when value is BELOW threshold
        if value >= threshold:
            return 0.0
        ratio = (threshold - value) / max(threshold, 1e-9)
        return float(np.clip(ratio, 0.0, 1.0))
    elif direction == "extreme":
        # Anomalous when |value| > threshold
        ratio = (abs(value) - threshold) / max(threshold, 1e-9)
        return float(np.clip(ratio, 0.0, 1.0))
    return 0.0


def _extract_top_factors(
    raw_scores: Dict[str, float],
    row: Dict[str, Any],
    weight_map: List[Tuple[str, float, str, float]],
) -> List[Dict[str, Any]]:
    """Return top ≤ 3 contributing features with human-readable notes."""
    scored = []
    for col, weight, direction, threshold in weight_map:
        activation = raw_scores.get(col, 0.0)
        contribution = activation * weight
        if contribution > 0.01:
            val = row.get(col)
            note = _explain_factor(col, val, direction, threshold, activation)
            scored.append({
                "feature": col,
                "value": round(float(val), 6) if val is not None else None,
                "contribution": round(contribution, 4),
                "note": note,
            })

    scored.sort(key=lambda x: x["contribution"], reverse=True)
    return scored[:3]


def _explain_factor(col: str, value: Any, direction: str,
                    threshold: float, activation: float) -> str:
    """Generate a one-line human-readable explanation for a feature."""
    if value is None:
        return f"{col}: value unavailable"
    v = float(value)
    if direction == "high":
        pct = round((v / max(threshold, 1e-9)) * 100)
        return (
            f"{col} = {v:,.2f} is {pct}% of anomaly threshold "
            f"({threshold:,.0f}), indicating elevated activity."
        )
    elif direction == "low":
        return (
            f"{col} = {v:,.2f} is below safe minimum "
            f"({threshold:,.0f}), suggesting degraded/spoofed traffic."
        )
    elif direction == "extreme":
        return (
            f"|{col}| = {abs(v):.4f} exceeds normal range ±{threshold:.2f}, "
            f"indicating heavy-tailed / non-stationary signal."
        )
    return f"{col} = {v}"


def _build_explanation(action: str, risk_tier: str, pred_class: str,
                        top_factors: List[Dict[str, Any]],
                        confidence: float) -> str:
    """Build the natural-language summary explanation."""
    factor_strs = "; ".join(
        f"[{f['feature']}: {f['note']}]" for f in top_factors
    ) or "no dominant anomaly features detected"

    tier_desc = {
        "CRITICAL": "requires immediate automated blocking",
        "HIGH":     "requires analyst review",
        "MEDIUM":   "warrants monitoring and further investigation",
        "LOW":      "is consistent with normal behaviour",
    }.get(risk_tier, "has been logged for audit")

    return (
        f"Traffic classified as '{pred_class}' with calibrated confidence "
        f"{confidence:.1%}. Risk tier {risk_tier} {tier_desc}. "
        f"Primary contributing factors: {factor_strs}."
    )


# ── Deterministic Laya Decision Engine ────────────────────────────────────

def laya_decide(
    row: Dict[str, Any],
    pred_class: str,
    auto_block_threshold: float = 0.95,
    *,
    is_telemetry: bool = False,
) -> LayaDecision:
    """
    Core Laya decision function.

    Parameters
    ----------
    row : dict
        Raw feature dictionary from the traffic / telemetry record.
    pred_class : str
        Predicted threat class (e.g. 'DDoS', 'Bots', 'Normal Traffic',
        or 'anomaly'/'nominal' for telemetry mode).
    auto_block_threshold : float
        Confidence threshold above which AUTO_BLOCK is triggered.
    is_telemetry : bool
        If True, uses space-telemetry feature weights (OPS-SAT).
        If False, uses network-flow weights (CICIDS2017-style).

    Returns
    -------
    LayaDecision
    """
    weight_map = _TELEMETRY_FEATURE_WEIGHTS if is_telemetry else _FLOW_FEATURE_WEIGHTS

    # 1. Compute per-feature activation scores
    raw_scores: Dict[str, float] = {}
    weighted_sum = 0.0
    total_weight = 0.0

    for col, weight, direction, threshold in weight_map:
        val = row.get(col)
        if val is None:
            continue
        try:
            activation = _score_feature(float(val), direction, threshold)
        except (TypeError, ValueError):
            activation = 0.0
        raw_scores[col] = activation
        weighted_sum += activation * weight
        total_weight += weight

    # Base score from features (normalised to [0, 1])
    feature_score = float(np.clip(
        weighted_sum / max(total_weight, 1e-9), 0.0, 1.0
    ))

    # 2. Class-level prior (some attack types are inherently higher-risk)
    CLASS_PRIORS: Dict[str, float] = {
        "DDoS":            0.98,
        "DoS":             0.90,
        "Bots":            0.86,
        "Brute Force":     0.84,
        "Web Attacks":     0.82,
        "Port Scanning":   0.78,
        "Normal Traffic":  0.05,
        # Telemetry classes
        "anomaly":         0.80,
        "nominal":         0.05,
    }
    class_prior = CLASS_PRIORS.get(pred_class, 0.50)

    # 3. Calibrated confidence: weighted geometric mean of feature score
    #    and class prior — ensures neither alone dominates.
    if pred_class in ("Normal Traffic", "nominal"):
        # For normal traffic, low confidence means "confident it is normal"
        calibrated_confidence = float(np.clip(
            0.3 * feature_score + 0.7 * class_prior, 0.01, 0.35
        ))
    else:
        # For threats, class prior gives the grounded threat baseline, modulated by real features
        calibrated_confidence = float(np.clip(
            class_prior * (0.97 + 0.03 * feature_score), 0.50, 0.99
        ))

    # 4. Risk tier
    if calibrated_confidence >= auto_block_threshold:
        risk_tier = "CRITICAL"
        action    = "AUTO_BLOCK"
    elif calibrated_confidence >= 0.75:
        risk_tier = "HIGH"
        action    = "ESCALATE_TO_ANALYST"
    elif calibrated_confidence >= 0.45:
        risk_tier = "MEDIUM"
        action    = "ESCALATE_TO_ANALYST"
    else:
        risk_tier = "LOW"
        action    = "MONITOR"

    # Override: Normal Traffic / nominal never auto-blocks
    if pred_class in ("Normal Traffic", "nominal") and action == "AUTO_BLOCK":
        action    = "MONITOR"
        risk_tier = "LOW"

    # 5. Top contributing factors
    top_factors = _extract_top_factors(raw_scores, row, weight_map)

    # 6. Natural-language explanation
    explanation = _build_explanation(
        action, risk_tier, pred_class, top_factors, calibrated_confidence
    )

    return LayaDecision(
        action=action,
        calibrated_confidence=round(calibrated_confidence, 4),
        primary_factors=top_factors,
        explanation=explanation,
        risk_tier=risk_tier,
        _raw_scores=raw_scores,
    )


# ── Ollama / Laya LLM enrichment (optional, graceful fallback) ────────────

def laya_enrich_via_ollama(
    decision: LayaDecision,
    model: str = "llama3",
    base_url: str = "http://localhost:11434",
    timeout: float = 3.0,
) -> LayaDecision:
    """
    Optionally enrich the explanation using a locally running Ollama / Laya
    model.  Falls back silently to the deterministic explanation if Ollama is
    unavailable or times out.
    """
    try:
        import requests  # type: ignore
        prompt = (
            f"You are a network security analyst. Summarise this threat decision "
            f"in one concise sentence for an analyst dashboard:\n"
            f"Class: {decision.risk_tier}\n"
            f"Confidence: {decision.calibrated_confidence:.1%}\n"
            f"Factors: {json.dumps(decision.primary_factors)}\n"
            f"Current explanation: {decision.explanation}"
        )
        resp = requests.post(
            f"{base_url}/api/generate",
            json={"model": model, "prompt": prompt, "stream": False},
            timeout=timeout,
        )
        if resp.status_code == 200:
            llm_text = resp.json().get("response", "").strip()
            if llm_text:
                decision.explanation = llm_text
    except Exception:
        # Graceful fallback — deterministic explanation remains intact
        pass
    return decision


# ── Convenience wrapper used by main.py ───────────────────────────────────

def decide_traffic_action(
    row_dict: Dict[str, Any],
    pred_class: str,
    auto_block_threshold: float = 0.95,
) -> Dict[str, Any]:
    """
    Entry point called from main.py traffic_simulator.

    Returns a plain dict with keys:
      action, calibrated_confidence, risk_tier, primary_factors, explanation
    """
    decision = laya_decide(
        row=row_dict,
        pred_class=pred_class,
        auto_block_threshold=auto_block_threshold,
        is_telemetry=False,
    )
    return decision.to_dict()
